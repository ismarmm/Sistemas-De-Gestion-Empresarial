PrimerNumero = int(input("Introduce el primer número: "))
SegundoNumero = int(input("Introduce el segundo número: "))

if PrimerNumero > SegundoNumero:
    print("El primer número es mayor que el segundo número")
elif PrimerNumero < SegundoNumero:
    print("El primer número es menor que el segundo número")
else:
    print("Los dos números son iguales")
